// Each project compiles .generated/kmp/<scenario>, written by scripts/extract-snippets.mjs.
// The pages target Android and iOS. A JVM target, with its fixtures, runs the Koin graph,
// because the graph can't run on Android or iOS without a device. iOS needs macOS.
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import org.jetbrains.compose.ComposeExtension

plugins {
    kotlin("multiplatform") apply false
    kotlin("plugin.compose") apply false
    kotlin("plugin.serialization") apply false
    id("com.android.library") apply false
    id("org.jetbrains.compose") apply false
    id("io.insert-koin.compiler.plugin") apply false
}

val versions = file("../../src/data/versions.ts").readText()
fun version(key: String) = Regex("""$key: '([^']+)'""").find(versions)!!.groupValues[1]
val isMac = System.getProperty("os.name").startsWith("Mac")

subprojects {
    val generated = rootProject.file("../.generated/kmp/$name")
    val usesPlugin = !name.endsWith("constructor")

    apply(plugin = "org.jetbrains.kotlin.multiplatform")
    apply(plugin = "org.jetbrains.kotlin.plugin.compose")
    apply(plugin = "org.jetbrains.kotlin.plugin.serialization")
    apply(plugin = "com.android.library")
    apply(plugin = "org.jetbrains.compose")
    if (usesPlugin) apply(plugin = "io.insert-koin.compiler.plugin")

    configure<com.android.build.api.dsl.LibraryExtension> {
        namespace = "com.jetbrains.kmpapp"
        compileSdk = 36
        defaultConfig.minSdk = version("androidMinSdk").toInt()
    }

    configure<KotlinMultiplatformExtension> {
        androidTarget()
        jvm()
        jvmToolchain(17)
        if (isMac) {
            iosSimulatorArm64 {
                binaries.framework {
                    baseName = "ComposeApp"
                    isStatic = true
                }
            }
        }

        val compose = project.extensions.getByType<ComposeExtension>().dependencies
        sourceSets.apply {
            listOf("commonMain", "commonTest", "androidMain", "iosMain", "jvmMain", "jvmTest").forEach { set ->
                maybeCreate(set).kotlin.srcDir(generated.resolve(set))
            }
            getByName("commonMain").dependencies {
                implementation(project.dependencies.platform("io.insert-koin:koin-bom:${version("koin")}"))
                implementation("io.insert-koin:koin-core")
                implementation("io.insert-koin:koin-compose-viewmodel-navigation")
                if (name.endsWith("annotations")) implementation("io.insert-koin:koin-annotations")
                implementation("io.ktor:ktor-client-core:${version("ktor")}")
                implementation("io.ktor:ktor-client-content-negotiation:${version("ktor")}")
                implementation("io.ktor:ktor-serialization-kotlinx-json:${version("ktor")}")
                implementation("org.jetbrains.androidx.navigation:navigation-compose:${version("navigationCompose")}")
                implementation("org.jetbrains.androidx.lifecycle:lifecycle-runtime-compose:${version("lifecycleCompose")}")
                // Generated by the wizard the page starts from.
                implementation(compose.runtime)
                implementation(compose.foundation)
                implementation(compose.material3)
                implementation(compose.ui)
            }
            if (name.contains("testing")) {
                getByName("commonTest").dependencies {
                    implementation("io.insert-koin:koin-test")
                    @OptIn(org.jetbrains.compose.ExperimentalComposeLibrary::class)
                    implementation(compose.uiTest)
                }
                getByName("jvmTest").dependencies {
                    implementation(compose.desktop.currentOs)
                }
            }
            getByName("androidMain").dependencies {
                implementation("io.ktor:ktor-client-okhttp:${version("ktor")}")
            }
            getByName("jvmMain").dependencies {
                implementation("io.ktor:ktor-client-okhttp:${version("ktor")}")
            }
            getByName("jvmTest").dependencies {
                implementation("org.jetbrains.kotlin:kotlin-test-junit")
            }
            if (isMac) {
                getByName("iosMain").dependencies {
                    implementation("io.ktor:ktor-client-darwin:${version("ktor")}")
                }
            }
        }
    }

    // What check:snippets runs in each project.
    tasks.register("checkScenario") {
        dependsOn("compileDebugKotlinAndroid", "jvmTest")
        if (isMac) dependsOn("compileKotlinIosSimulatorArm64", "compileTestKotlinIosSimulatorArm64")
    }
}
